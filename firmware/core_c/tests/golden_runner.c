int main(void) {
    run_generated_limits_cases();
    run_generated_safety_cases();
    run_generated_control_cases();
    if (g_failures == 0) {
        printf("golden_runner: all cases passed\n");
        return 0;
    }
    fprintf(stderr, "golden_runner: %d failures\n", g_failures);
    return 1;
}
